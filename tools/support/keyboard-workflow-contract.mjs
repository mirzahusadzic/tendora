export function reviewedTransition(id, evidence, outcome, { limit = null } = {}) {
  const contract = keyboardContracts.find((item) => item.id === id);
  if (!contract) throw new Error(`Undeclared keyboard transition: ${id}`);
  if (!evidence || !outcome) throw new Error(`Evidence and observed result required: ${id}`);
  return {
    ...contract,
    evidence,
    outcome,
    grades: {
      functionality: 'PASS: asserted through the real key controller',
      usefulness: 'PASS: ' + contract.purpose,
      ease: 'PASS: keyboard reachable; return path exercised',
      fit: 'PASS: language authoring, source hierarchy or attributed checking',
      result: limit ? 'LIMITED: ' + limit : 'PASS: ' + outcome,
    },
  };
}
